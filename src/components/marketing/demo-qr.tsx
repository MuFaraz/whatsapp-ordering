import { DEMO_SLUG } from "@/config/site";
import { buildMenuUrl } from "@/lib/app-url";
import { getAppUrl } from "@/lib/app-url.server";
import { generateMenuQr } from "@/lib/qr";

/** Server-rendered QR code for the demo menu, to scan with a real phone. */
export async function DemoQr({ className }: { className?: string }) {
  const url = buildMenuUrl(await getAppUrl(), DEMO_SLUG);
  const { svg } = await generateMenuQr(url);
  return (
    <figure className={className}>
      <div
        role="img"
        aria-label={`QR code for the demo menu at ${url}`}
        className="rounded-2xl bg-white p-3 shadow-sm ring-1 ring-black/5 [&_svg]:h-auto [&_svg]:w-full"
        // Trusted SVG generated by the qrcode library from our own URL.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
      <figcaption className="mt-2 text-center text-xs text-muted-foreground">
        Scan with your phone camera
      </figcaption>
    </figure>
  );
}
